// Writes supabase/seed.sql from src/lib/content/defaults.ts.
// Run: node scripts/generate-seed.ts > supabase/seed.sql
import { defaultContent } from "../src/lib/content/defaults.ts";

const text = (value: string | null) => (value === null ? "null" : `'${value.replaceAll("'", "''")}'`);
const json = (value: unknown) => (value === null ? "null" : `${text(JSON.stringify(value))}::jsonb`);
const num = (value: number | null | undefined) => (value === null || value === undefined ? "null" : String(value));
const bool = (value: boolean) => (value ? "true" : "false");

function insert(table: string, columns: string[], rows: string[][]) {
  const values = rows.map((row) => `  (${row.join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values};\n`;
}

const { settings, tours, vehicles, places, routes, reviews, faqs } = defaultContent;

const sql = [
  "-- GENERATED by scripts/generate-seed.ts from src/lib/content/defaults.ts. Run once on an empty database.",
  "begin;",
  insert(
    "site_settings",
    ["business_name", "site_url", "whatsapp_number", "phone_display", "email", "address", "google_rating", "google_reviews_url", "instagram_url", "idr_per_usd"],
    [
      [
        text(settings.businessName),
        text(settings.siteUrl),
        text(settings.whatsappNumber),
        text(settings.phoneDisplay),
        text(settings.email),
        text(settings.address),
        text(settings.googleRating),
        text(settings.googleReviewsUrl),
        text(settings.instagramUrl),
        num(settings.idrPerUsd),
      ],
    ],
  ),
  insert(
    "tours",
    ["slug", "code", "length", "interests", "price_from_idr", "photo", "photo_credit", "text", "position", "published"],
    tours.map((tour, index) => [
      text(tour.slug),
      text(tour.code),
      text(tour.length),
      `array[${tour.interests.map(text).join(", ")}]::text[]`,
      num(tour.priceFromIdr),
      text(tour.photo),
      json(tour.photoCredit),
      json(tour.text),
      num(index),
      bool(tour.published),
    ]),
  ),
  insert(
    "vehicles",
    ["id", "name", "seats", "max_passengers", "day_with_driver_idr", "day_with_driver_and_fuel_idr", "transfer_base_idr", "transfer_per_km_idr", "transfer_minimum_idr", "position", "published"],
    vehicles.map((car, index) => [
      text(car.id),
      text(car.name),
      text(car.seats),
      num(car.maxPassengers),
      num(car.dayWithDriverIdr),
      num(car.dayWithDriverAndFuelIdr),
      num(car.transferRate?.baseIdr),
      num(car.transferRate?.perKmIdr),
      num(car.transferRate?.minimumIdr),
      num(index),
      bool(car.published),
    ]),
  ),
  insert(
    "places",
    ["id", "kind", "lat", "lng", "name", "position", "published"],
    places.map((place, index) => [text(place.id), text(place.kind), num(place.lat), num(place.lng), json(place.name), num(index), bool(place.published)]),
  ),
  insert(
    "popular_routes",
    ["from_place", "to_place", "position"],
    routes.map((route, index) => [text(route.from), text(route.to), num(index)]),
  ),
  insert(
    "reviews",
    ["guest_name", "origin", "quote", "tour_slug", "position", "published"],
    reviews.map((review, index) => [
      text(review.guestName),
      json(review.origin),
      json(review.quote),
      text(review.tourSlug),
      num(index),
      bool(review.published),
    ]),
  ),
  insert(
    "faqs",
    ["question", "answer", "position", "published"],
    faqs.map((faq, index) => [json(faq.question), json(faq.answer), num(index), bool(faq.published)]),
  ),
  "commit;",
].join("\n");

